/**
 * 写メ日記一覧（投稿日時は本日から過去2週間に自動割当）
 */
function getDiaryEntries(): array
{
  global $diaryPosts, $girls;

  $girlNames = array_column($girls, 'name');
  $count = count($diaryPosts);
  $entries = [];

  foreach ($diaryPosts as $index => $post) {
    $daysAgo = (int) floor($index * 13 / max($count - 1, 1));
    $hours = [8, 10, 12, 14, 16, 18, 20, 22];
    $hour = $hours[$index % count($hours)];
    $minute = ($index * 7) % 60;
    $postedAt = strtotime("-{$daysAgo} days", strtotime('today')) + ($hour * 3600) + ($minute * 60);

    $entries[] = [
      'img' => $post['img'],
      'body' => $post['body'],
      'name' => $post['name'] ?? $girlNames[$index % count($girlNames)],
      'posted_at' => $postedAt,
      'posted_at_display' => date('Y/m/d H:i', $postedAt),
    ];
  }

  usort($entries, static fn(array $a, array $b): int => $b['posted_at'] <=> $a['posted_at']);

  return $entries;
}

/**
 * 写メ日記一覧（ページネーション付き）
 */
function getPaginatedDiaryEntries(int $page = 1, int $perPage = 5): array
{
  $entries = getDiaryEntries();
  $total = count($entries);
  $totalPages = max(1, (int) ceil($total / $perPage));
  $page = max(1, min($page, $totalPages));
  $offset = ($page - 1) * $perPage;

  return [
    'entries' => array_slice($entries, $offset, $perPage),
    'page' => $page,
    'perPage' => $perPage,
    'total' => $total,
    'totalPages' => $totalPages,
  ];
}

function getDiaryPageUrl(int $page): string
{
  return $page <= 1 ? 'diary.php' : 'diary.php?page=' . $page;
}

/**
 * 写メ日記の最新記事を取得（トップページ用）
 */
function getLatestDiaryEntries(int $limit = 3): array
{
  return array_slice(getDiaryEntries(), 0, $limit);
}

/**
 * トップ用に本文を短く整形
 */
function getDiaryExcerpt(string $body, int $length = 72): string
{
  $text = preg_replace("/\r\n|\r|\n/", ' ', $body);
  $text = trim($text);

  if (mb_strlen($text) <= $length) {
    return $text;
  }

  return mb_substr($text, 0, $length) . '…';
}
